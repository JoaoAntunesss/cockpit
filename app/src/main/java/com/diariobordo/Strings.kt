/** Idioma da app: 0 = o do telemóvel (português se for português, senão inglês), 1 = português, 2 = inglês. */
object Lang {
    var mode by mutableIntStateOf(0)
    fun load(ctx: Context) { mode = ctx.getSharedPreferences("diario", 0).getInt("lang", 0) }
    fun set(ctx: Context, v: Int) { mode = v; ctx.getSharedPreferences("diario", 0).edit().putInt("lang", v).apply() }
    fun en(): Boolean = when (mode) { 1 -> false; 2 -> true; else -> Locale.getDefault().language != "pt" }
}

/** Texto em português; devolve a versão inglesa quando a app está em inglês. */
fun tr(pt: String): String = if (Lang.en()) (EN_TEXT[pt] ?: pt) else pt

/** Para frases com valores: escreve as duas versões. */
fun t(pt: String, en: String): String = if (Lang.en()) en else pt

